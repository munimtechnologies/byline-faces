class TimeUp(Exception):
    pass


class Pacer:
    """One Wayback request at a time, a pause between requests, back off on 429."""

    def __init__(self, fetch, pause=1.0, log=print, max_429=8):
        self.fetch, self.pause, self.log, self.max_429 = fetch, pause, log, max_429
        self.requests = self.errors = self.n429 = 0

    def get(self, url, accept, deadline, max_bytes=3_000_000, timeout=45):
        for attempt in (0, 1):
            if time.time() > deadline or self.n429 >= self.max_429:
                raise TimeUp()
            time.sleep(self.pause)
            self.requests += 1
            try:
                st, final, ct, body = self.fetch(url, max_bytes=max_bytes, timeout=timeout,
                                                 accept=accept)
            except Exception:
                self.errors += 1
                return 0, url, "", b""
            if st != 429:
                return st, final, ct, body
            self.n429 += 1
            self.log("wayback 429 number", self.n429, "; pausing 60 s")
            time.sleep(60)
        return 429, url, "", b""


def image_dhash(data):
    try:
        import cv2
        import numpy as np
        img = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_GRAYSCALE)
        if img is None:
            return None
        small = cv2.resize(img, (9, 8), interpolation=cv2.INTER_AREA)
        return "%016x" % dhash_bits(small.tolist())
    except Exception:
        return None


