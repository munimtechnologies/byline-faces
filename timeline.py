def variants(page):
    """The page with and without a trailing slash (the CDX index keeps them apart)."""
    base = (page or "").rstrip("/")
    return [base, base + "/"] if base else []


def cdx_exact_url(page, limit=2000):
    """CDX query: every 200 capture of exactly this URL, at most one per month."""
    params = [("url", page), ("matchType", "exact"), ("output", "json"),
              ("fl", "timestamp,original"), ("filter", "statuscode:200"),
              ("collapse", "timestamp:6"), ("limit", str(limit))]
    return WAYBACK + "/cdx/search/cdx?" + urllib.parse.urlencode(params)


def wayback(ts, original, flag):
    return "%s/web/%s%s/%s" % (WAYBACK, ts, flag, original)


def parse_cdx(cdx_json):
    """[(timestamp, original)] from CDX output=json (the first row is the header)."""
    if not isinstance(cdx_json, list) or not cdx_json:
        return []
    header = cdx_json[0]
    try:
        ti, oi = header.index("timestamp"), header.index("original")
    except (ValueError, AttributeError):
        return []
    return [(str(r[ti]), r[oi]) for r in cdx_json[1:]
            if isinstance(r, list) and len(r) > max(ti, oi)]


def valid_ts(ts):
    s = str(ts or "")
    return len(s) >= 8 and s[:8].isdigit()


def pick_captures(rows, k):
    """At most one capture per month (the earliest), then k spread evenly over the page's
    archived life, always including the first and the last."""
    by_month = {}
    for ts, orig in rows:
        ts = str(ts)
        if not valid_ts(ts):
            continue
        m = ts[:6]
        if m not in by_month or ts < by_month[m][0]:
            by_month[m] = (ts, orig)
    items = [by_month[m] for m in sorted(by_month)]
    n = len(items)
    if k <= 0 or n == 0:
        return []
    if n <= k:
        return items
    if k == 1:
        return [items[0]]
    idx = sorted({int(math.floor(i * (n - 1) / (k - 1) + 0.5)) for i in range(k)})
    return [items[i] for i in idx]


def dhash_bits(rows):
    """64-bit difference hash from an 8 x 9 grid of grey levels (row-major, left > right)."""
    if len(rows) != 8 or any(len(r) != 9 for r in rows):
        raise ValueError("need 8 rows of 9 values")
    v = 0
    for r in rows:
        for x in range(8):
            v = (v << 1) | (1 if r[x] > r[x + 1] else 0)
    return v


def parse_hash(h):
    if isinstance(h, int):
        return h
    if isinstance(h, str) and h:
        try:
            return int(h, 16)
        except ValueError:
            return None
    return None


def hamming(a, b):
    return bin(a ^ b).count("1")


def host_of(url):
    u = url or ""
    h = urlparse(u if "://" in u else "http://" + u).netloc.lower()
    return h[4:] if h.startswith("www.") else h


def order_candidates(cands, tokens):
    """Pictures whose URL names the persona first, then JSON-LD Person images, then <img>
    headshots, then og/twitter images (stable within each rank)."""
    toks = [t.lower() for t in tokens if t]

    def rank(c):
        u = (c.get("url") or "").lower()
        if any(t in u for t in toks):
            return 0
        return {"jsonld": 1, "img": 2}.get(c.get("kind"), 3)

    return sorted(cands, key=rank)


def cluster_observations(obs, max_dist=10):
    """Group one persona's observations into distinct pictures: same SHA-256, or a
    difference hash within max_dist bits of the cluster's first picture."""
    clusters = []
    for o in sorted(obs, key=lambda r: (str(r.get("capture") or ""), r.get("sha256") or "")):
        h = parse_hash(o.get("dhash"))
        hit = None
        for c in clusters:
            if o.get("sha256") in c["shas"] or (
                    h is not None and c["h"] is not None and hamming(h, c["h"]) <= max_dist):
                hit = c
                break
        if hit is None:
            hit = {"h": h, "shas": set(), "obs": []}
            clusters.append(hit)
        hit["obs"].append(o)
        hit["shas"].add(o.get("sha256"))
    return clusters


def median(vals):
    v = sorted(vals)
    n = len(v)
    if not n:
        return None
    return v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2.0


def cluster_summary(c, t=0.5):
    obs = c["obs"]
    caps = sorted(str(o.get("capture") or "") for o in obs)
    per_sha = {}
    for o in obs:
        per_sha.setdefault(o.get("sha256"), o)
    cfs = [o["cf"] for o in per_sha.values() if o.get("cf") is not None]
    med = median(cfs)
    return {"first_seen": caps[0], "last_seen": caps[-1], "observations": len(obs),
            "images": len(per_sha), "hosts": sorted({host_of(o.get("page")) for o in obs}),
            "cf_median": None if med is None else round(med, 4),
            "cf_flag": None if med is None else med >= t,
            "eye_flag": any(bool(o.get("aligned") or o.get("centred_level"))
                            for o in per_sha.values()),
            "sha256": sorted(k for k in per_sha if k),
            "dhash": None if c["h"] is None else "%016x" % c["h"]}


def wilson(k, n, z=1.96):
    if not n:
        return None
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return [round(max(0.0, centre - half), 4), round(min(1.0, centre + half), 4)]


def binom_tail(k, n):
    """P(X >= k) for X ~ Binomial(n, 1/2)."""
    if n <= 0:
        return None
    return sum(math.comb(n, i) for i in range(k, n + 1)) / float(2 ** n)


def analyse(obs, stats=None, cf_repro_ok=None, t=0.5, max_dist=10):
    """The pre-registered summary (PREREGISTRATION-4.md)."""
    stats = stats or {}
    personas = {}
    for p in PERSONAS:
        mine = [o for o in obs if o.get("persona") == p["id"]]
        cl = [cluster_summary(c, t) for c in cluster_observations(mine, max_dist)]
        cl.sort(key=lambda c: (c["first_seen"], c["last_seen"]))
        e = {"case": p["case"], "faces_seen": len(mine), "distinct_headshots": len(cl),
             "headshots": cl, "direction": None}
        e.update(stats.get(p["id"], {}))
        if len(cl) >= 2 and cl[0]["cf_median"] is not None and cl[-1]["cf_median"] is not None:
            a, b = cl[0]["cf_median"], cl[-1]["cf_median"]
            e["direction"] = "up" if b > a else "down" if b < a else "equal"
        personas[p["id"]] = e

    ctrl = {}
    for o in obs:
        if o.get("cf") is None or not o.get("sha256"):
            continue
        cap = str(o.get("capture") or "")
        its = str(o.get("img_capture") or cap)
        if valid_ts(cap) and valid_ts(its) and cap < STYLEGAN_PUBLIC and its < STYLEGAN_PUBLIC:
            ctrl.setdefault(o["sha256"], o["cf"])
    k = sum(1 for v in ctrl.values() if v >= t)
    n = len(ctrl)
    control = {"rule": "distinct pictures whose page and image captures both precede %s"
                       % STYLEGAN_PUBLIC,
               "n": n, "cf_flagged": k, "rate": k / n if n else None, "wilson95": wilson(k, n),
               "cf_scores": sorted(round(v, 4) for v in ctrl.values())}

    late = [c for e in personas.values() for c in e["headshots"]
            if c["first_seen"] >= DIFFUSION_ERA and c["cf_flag"] is True]
    late_eye = sum(1 for c in late if c["eye_flag"])
    diffusion_era = {"rule": "distinct pictures first seen on or after %s that Community "
                             "Forensics flags" % DIFFUSION_ERA,
                     "n": len(late), "eye_flagged": late_eye,
                     "eye_share": late_eye / len(late) if late else None}
    return {"version": __version__, "threshold_cf": t, "dhash_max_dist": max_dist,
            "cf_repro_ok": cf_repro_ok, "personas": personas, "control_pre2019": control,
            "diffusion_era_flagged": diffusion_era, "cases": CASE_SOURCES}


def grade(summary):
    """Mechanical verdicts for T1-T8 (rules in PREREGISTRATION-4.md)."""
    t = summary["threshold_cf"]
    P = summary["personas"]
    cf_ok = summary.get("cf_repro_ok") is True
    pg = [pid for pid, e in P.items() if e["case"] == PG_CASE]
    out = {}
    n1 = sum(1 for pid in pg if P[pid]["distinct_headshots"] >= 1)
    out["T1"] = {"verdict": "true" if n1 >= 3 else "false", "value": n1}
    n2 = sum(1 for pid in pg if P[pid]["distinct_headshots"] >= 2)
    out["T2"] = {"verdict": "no_data" if n1 < 2 else ("true" if n2 >= 2 else "false"),
                 "value": n2}

    def cf_pred(name, fn):
        if not cf_ok:
            out[name] = {"verdict": "invalid", "reason": "Community Forensics validity check "
                                                         "did not pass"}
        else:
            out[name] = fn()

    def t3():
        dirs = [e["direction"] for e in P.values() if e["direction"] in ("up", "down")]
        up, n = dirs.count("up"), len(dirs)
        if n < 3:
            return {"verdict": "no_data", "up": up, "n": n}
        return {"verdict": "true" if 2 * up > n else "false", "up": up, "n": n,
                "p_one_sided": binom_tail(up, n)}

    def t4():
        e = P.get("nikolai-kuznetsov") or {"headshots": []}
        cl = [c for c in e["headshots"] if c["cf_median"] is not None]
        if len(cl) < 2:
            return {"verdict": "no_data", "scored_headshots": len(cl)}
        ok = cl[0]["cf_median"] < t and cl[-1]["cf_median"] >= t
        return {"verdict": "true" if ok else "false", "first_cf": cl[0]["cf_median"],
                "last_cf": cl[-1]["cf_median"]}

    def t5():
        c = summary["control_pre2019"]
        if c["n"] < 5:
            return {"verdict": "no_data", "n": c["n"]}
        return {"verdict": "true" if c["rate"] <= 0.10 else "false", "n": c["n"],
                "rate": c["rate"], "wilson95": c["wilson95"]}

    def t6():
        d = summary["diffusion_era_flagged"]
        if d["n"] == 0:
            return {"verdict": "no_data", "n": 0}
        return {"verdict": "true" if d["eye_share"] < 0.5 else "false", "n": d["n"],
                "eye_share": d["eye_share"]}

    def no_flag(pid):
        def fn():
            cl = [c for c in (P.get(pid) or {"headshots": []})["headshots"]
                  if c["cf_flag"] is not None]
            if not cl:
                return {"verdict": "no_data", "scored_headshots": 0}
            flagged = sum(1 for c in cl if c["cf_flag"])
            return {"verdict": "true" if flagged == 0 else "false",
                    "scored_headshots": len(cl), "flagged": flagged}
        return fn

    cf_pred("T3", t3)
    cf_pred("T4", t4)
    cf_pred("T5", t5)
    cf_pred("T6", t6)
    cf_pred("T7", no_flag("joe-liebkind"))
    cf_pred("T8", no_flag("luis-aureliano"))
    return {"version": __version__, "cf_repro_ok": summary.get("cf_repro_ok"), "grades": out}


def public_lines(obs):
    """One public line per observation (all personas were named in published reporting)."""
    out = []
    for o in sorted(obs, key=lambda r: (r.get("persona") or "", str(r.get("capture") or ""))):
        out.append({"persona": o.get("persona"), "case": o.get("case"),
                    "archived_page": wayback(o.get("capture"), o.get("page"), ""),
                    "wayback_image": o.get("wayback_img") or "", "capture": o.get("capture"),
                    "img_capture": o.get("img_capture"), "sha256": o.get("sha256"),
                    "dhash": o.get("dhash"), "eye_aligned": bool(o.get("aligned")),
                    "eye_centred_level": bool(o.get("centred_level")),
                    "cf": None if o.get("cf") is None else round(o["cf"], 4)})
    return out


